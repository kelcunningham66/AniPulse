# service, region, available, is_new, note
def _grid(services: dict[str, dict[str, tuple[bool, bool, str]]]) -> list[tuple]:
    rows = []
    for service, regions in services.items():
        for region, (available, is_new, note) in regions.items():
            rows.append((service, region, available, is_new, note))
    return rows


def _regions(us, gb, jp, ca, note=""):
    return {
        "US": (us[0], us[1], note if us[0] else ""),
        "GB": (gb[0], gb[1], note if gb[0] else ""),
        "JP": (jp[0], jp[1], note if jp[0] else ""),
        "CA": (ca[0], ca[1], note if ca[0] else ""),
    }


